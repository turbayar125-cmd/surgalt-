create or replace function public.send_license_digest(force boolean default false) returns int
language plpgsql security definer set search_path = public, extensions as $$
declare
  cfg   public.settings;
  api   text;
  today date := (now() at time zone 'Asia/Ulaanbaatar')::date;
  d     record;
  r     record;
  cc    text[];
  rcpt  text[];
  rows  text;
  n     int;
  nbad  int;
  sent  int := 0;
  hide  int;
begin
  if auth.uid() is not null and not public.is_admin() then raise exception 'Зөвхөн админ илгээх эрхтэй'; end if;
  select * into cfg from public.settings where id = 1;
  if not force and (cfg.lic_weekday = 0 or extract(isodow from today) <> cfg.lic_weekday) then return 0; end if;
  select decrypted_secret into api from vault.decrypted_secrets where name = 'resend_api_key' limit 1;
  if api is null then raise exception 'Resend API түлхүүр Vault-д алга. README-ийн 5-р алхмыг хийнэ үү.'; end if;
  hide := coalesce(cfg.hide_expired_days, 500);
  cc := array(select trim(x) from unnest(string_to_array(coalesce(cfg.lic_cc, ''), ',')) x where trim(x) <> '');

  for d in select dp.id, dp.name, nullif(trim(dp.email), '') as email from public.departments dp order by dp.sort, dp.name loop
    rows := ''; n := 0; nbad := 0;
    for r in
      with cur as (
        select distinct on (t.employee_id, t.training_type_id) t.*
        from public.trainings t order by t.employee_id, t.training_type_id, t.completed_on desc, t.expires_on desc, t.id desc)
      select e.full_name, e.emp_code, e.position, tt.name as lic, c.certificate_no, c.expires_on, (c.expires_on - today) as days_left
      from cur c
      join public.employees e on e.id = c.employee_id and e.active and e.department_id = d.id
      join public.training_types tt on tt.id = c.training_type_id
      where coalesce(tt.is_license, tt.name ~* '^\s*mgl\M|licen[cs]e|үнэмлэх')
        and c.expires_on - today <= cfg.lic_days
        and (hide <= 0 or c.expires_on - today >= -hide)
      order by c.expires_on
    loop
      n := n + 1; if r.days_left < 0 then nbad := nbad + 1; end if;
