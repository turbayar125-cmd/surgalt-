-- ---------- Хүснэгтүүд ----------
create table if not exists public.departments (
  id          bigint generated by default as identity primary key,
  name        text not null unique,
  sort        int  not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.employees (
  id            bigint generated by default as identity primary key,
  emp_code      text unique,
  full_name     text not null,
  department_id bigint references public.departments(id) on delete set null,
  position      text,
  email         text,
  phone         text,
  photo_url     text,
  active        boolean not null default true,
  created_at    timestamptz not null default now()
);
-- шинэ баганууд (хуучин сан дээр ч нэмэгдэнэ)
alter table public.employees add column if not exists manager_id bigint references public.employees(id) on delete set null;
alter table public.employees add column if not exists hired_on   date;
alter table public.employees add column if not exists notes      text;
create index if not exists employees_dept_idx    on public.employees(department_id);
create index if not exists employees_manager_idx on public.employees(manager_id);

create table if not exists public.training_types (
  id              bigint generated by default as identity primary key,
  name            text not null unique,
  validity_months int  not null default 12 check (validity_months > 0),
  description     text,
  created_at      timestamptz not null default now()
);

create table if not exists public.trainings (
  id               bigint generated by default as identity primary key,
  employee_id      bigint not null references public.employees(id) on delete cascade,
  training_type_id bigint not null references public.training_types(id) on delete cascade,
  completed_on     date not null,
  expires_on       date not null,
  certificate_no   text,
  provider         text,
  notes            text,
  created_at       timestamptz not null default now(),
  check (expires_on >= completed_on)
);
create index if not exists trainings_emp_type_idx on public.trainings(employee_id, training_type_id, expires_on desc);

create table if not exists public.reminder_log (
  id          bigint generated by default as identity primary key,
  training_id bigint not null references public.trainings(id) on delete cascade,
  days_before int not null,
  recipients  jsonb,
  sent_at     timestamptz not null default now(),
  unique (training_id, days_before)
);

create table if not exists public.settings (
  id            int primary key default 1 check (id = 1),
